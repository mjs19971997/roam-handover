# -*- coding: utf-8 -*-
"""Mobility profiles.

A profile fixes the speed range and the motion model of a user population; the
trajectories themselves are generated by `roam.simulator.gen_traj`:

  * "rwp"    random waypoint in the open area;
  * "grid"   Manhattan-style street grid (150 m blocks, turns at intersections);
  * "linear" straight track: three highway lanes, or, with group=True, one shared
             railway line on which all users move together at a common speed.
"""
from dataclasses import dataclass


@dataclass(frozen=True)
class MobilityProfile:
    """Speed range [m/s] and motion model of one user population."""
    key: str
    name: str
    v_min: float      # [m/s]
    v_max: float
    model: str        # "rwp" | "grid" | "linear"
    group: bool = False   # group mobility: all users share one track and one speed (train)


PROFILES = [
    MobilityProfile("pedestrian", "Pedestrian",         0.8,  2.0, "rwp"),
    MobilityProfile("vehicular",  "Urban vehicular",    8.0, 16.0, "rwp"),
    MobilityProfile("street",     "Urban street grid",  8.0, 16.0, "grid"),
    MobilityProfile("highway",    "Highway driving",   22.0, 33.0, "linear"),
    MobilityProfile("train",      "High-speed train",  40.0, 60.0, "linear", True),
]
PROF_BY_KEY = {p.key: p for p in PROFILES}
PROF_KEYS = [p.key for p in PROFILES]
